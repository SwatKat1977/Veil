import http
import json
import quart
from weaver_framework.microservice.api_response import ApiResponse
from weaver_framework.microservice.base_api_route import BaseApiRoute, validate_json
from weaver_framework.microservice.http_content_type import HttpContentType
from veil.identity_service.routes.route_injections import RouteInjections
from veil.identity_service.routes.common_request_json_schema import (
    EMAIL_ADDRESS_SCHEMA, PASSWORD_SCHEMA)
from veil.identity_service.models.account_creation_result import \
    AccountCreationResult


SCHEMA_REGISTER_ACCOUNT_REQUEST: dict = {
    "$schema": "http://json-schema.org/draft-07/schema#",

    "type": "object",
    "additionalProperties": False,

    "properties":
    {
        "display_name":
            {
                "type": "string",
                "minLength": 4,
                "maxLength": 64
            },
        "email_address": EMAIL_ADDRESS_SCHEMA,
        "password": PASSWORD_SCHEMA
    },
    "required": ["display_name", "email_address", "password"]
}
"""JSON schema for account registration requests.

The request body must contain a display name, email address, and
password used to create a new account.

Schema Rules:
    * ``display_name`` must be between 4 and 64 characters.
    * ``email_address`` must be a valid email address and between
      3 and 320 characters.
    * ``password`` must be between 8 and 128 characters.
    * Additional unknown properties are rejected.
"""


def create_blueprint(injections: RouteInjections) -> quart.Blueprint:
    """Create the account registration API blueprint.

    Registers the ``POST /accounts/register`` endpoint and binds it
    to :class:`RegisterAccountRoute`.

    Args:
        injections: Shared route dependencies and service injections.

    Returns:
        The configured Quart blueprint containing the account
        registration endpoint.
    """
    new_route = RegisterAccountRoute(injections)

    blueprint = quart.Blueprint('register_account', __name__)

    injections.logger.debug("=> %s POST /accounts/register",
                            'Register new account'.ljust(40))

    @blueprint.route('/accounts/register', methods=['POST'])
    async def register_account_request() -> quart.Response:
        """Handle incoming account registration requests.

        Returns:
            The HTTP response generated by the register account route.
        """
        # pylint: disable=no-value-for-parameter
        return await new_route.register_account()

    return blueprint


class RegisterAccountRoute(BaseApiRoute):
    """Route handler for account registration operations."""

    def __init__(self, injections: RouteInjections) -> None:
        """Initialize the register account route handler.

        Args:
            injections: Shared route dependencies and injected services.
        """
        self._logger = injections.logger.getChild(__name__)
        self._injections: RouteInjections = injections

    @validate_json(SCHEMA_REGISTER_ACCOUNT_REQUEST)
    async def register_account(self,
                               request_msg: ApiResponse) -> quart.Response:
        """Register a new user account.

        Validates the incoming registration request, checks for
        duplicate email addresses and display names, hashes the
        supplied password, and creates a new account record.

        Args:
            request_msg: Parsed API request containing the validated
                registration payload.

        Returns:
            A Quart HTTP response containing either the newly created
            user ID or an error response describing the failure.
        """

        email_address: str = request_msg.body["email_address"].strip().lower()
        display_name: str = request_msg.body["display_name"].strip()
        raw_password: str = request_msg.body["password"]

        account_svc = self._injections.account_service

        if account_svc.email_address_exists(email_address):
            return quart.Response(
                json.dumps({"error": "email address already exists"}),
                status=http.HTTPStatus.CONFLICT,
                content_type=HttpContentType.JSON)

        if account_svc.display_name_exists(display_name):
            return quart.Response(
                json.dumps({"error": "display name already exists"}),
                status=http.HTTPStatus.CONFLICT,
                content_type=HttpContentType.JSON)

        result: AccountCreationResult | None = \
            self._injections.account_service.create_account(
                email_address,
                display_name, raw_password)

        if result.user_id is None:
            self._logger.error(
                "Failed to create account for email address '%s'",
                email_address)
            return quart.Response(
                json.dumps({"error": "failed_to_create_account"}),
                status=http.HTTPStatus.INTERNAL_SERVER_ERROR,
                content_type=HttpContentType.JSON)

        response_body: dict = {"user_id": result.user_id}
        return quart.Response(json.dumps(response_body),
                              status=http.HTTPStatus.CREATED,
                              content_type=HttpContentType.JSON)
